// Dataverse external-tool integration: reads the launch parameters Dataverse
// appends to the tool URL, then talks to the Dataverse API to load the file
// being reviewed and (optionally) save the reviewed JSON back to Dataverse.
//
// Launch URL looks like:
//   http://localhost:5173?fileid=42&siteUrl=http://localhost:8080&key=<token>
//     &datasetid=doi:...&datasetversion=1.0&locale=en
// See https://guides.dataverse.org/en/latest/api/external-tools.html

const PARAM_NAMES = ['fileid', 'siteurl', 'key', 'datasetid', 'datasetversion', 'locale'];

/** Reads fileid/siteUrl/key/etc from the current URL. Returns null if this isn't a Dataverse launch. */
export function getDataverseContext() {
  if (typeof window === 'undefined') return null;
  const params = new URLSearchParams(window.location.search);
  const values = {};
  for (const [key, value] of params) {
    const name = key.toLowerCase();
    if (PARAM_NAMES.includes(name)) values[name] = value;
  }
  if (!values.fileid || !values.siteurl) return null;
  return {
    fileId: values.fileid,
    siteUrl: values.siteurl.replace(/\/+$/, ''),
    apiToken: values.key || null,
    datasetId: values.datasetid || null,
    datasetVersion: values.datasetversion || null,
    locale: values.locale || null,
  };
}

const withKey = (url, apiToken) =>
  apiToken ? `${url}${url.includes('?') ? '&' : '?'}key=${encodeURIComponent(apiToken)}` : url;

/** Fetches the file's label (for display) and content from Dataverse. */
export async function fetchDataverseFile(ctx) {
  let filename = `dataverse-file-${ctx.fileId}`;
  try {
    const metaRes = await fetch(withKey(`${ctx.siteUrl}/api/files/${ctx.fileId}`, ctx.apiToken));
    if (metaRes.ok) {
      const meta = await metaRes.json();
      filename = meta?.data?.label ?? meta?.data?.dataFile?.filename ?? filename;
    }
  } catch {
    // Display name is cosmetic only; fall back to the default above.
  }

  const dataRes = await fetch(withKey(`${ctx.siteUrl}/api/access/datafile/${ctx.fileId}`, ctx.apiToken));
  if (!dataRes.ok) {
    throw new Error(
      `Dataverse returned ${dataRes.status} fetching file ${ctx.fileId}. Check the file ID, site URL and API token.`
    );
  }
  const text = await dataRes.text();
  let data;
  try {
    data = JSON.parse(text);
  } catch {
    throw new Error('The Dataverse file is not valid JSON.');
  }
  return { data, filename };
}

/**
 * Adds the reviewed JSON as a new file in the dataset, alongside the original enriched file
 * (which is left untouched). Requires the dataset's persistent ID (datasetid launch parameter).
 */
export async function addDataverseFile(ctx, filename, jsonText) {
  if (!ctx.datasetId) {
    throw new Error(
      'Dataverse did not pass a dataset ID to this tool, so the reviewed file cannot be added to the dataset.'
    );
  }
  const url = withKey(
    `${ctx.siteUrl}/api/datasets/:persistentId/add?persistentId=${encodeURIComponent(ctx.datasetId)}`,
    ctx.apiToken
  );
  const form = new FormData();
  form.append('file', new Blob([jsonText], { type: 'application/json' }), filename);
  form.append('jsonData', JSON.stringify({ description: 'Reviewed metadata, generated by Variable Metadata Editor.' }));
  const res = await fetch(url, { method: 'POST', body: form });
  if (!res.ok) {
    const body = await res.text().catch(() => '');
    throw new Error(`Dataverse rejected the upload (${res.status}). ${body}`.trim());
  }
  return res.json();
}
